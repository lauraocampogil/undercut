export type AppLang = 'en' | 'fr' | 'es';
export const APP_LANGS: [AppLang, string][] = [
	['en', 'EN'],
	['fr', 'FR'],
	['es', 'ES']
];

/** Read the language from the cookies (works with SvelteKit's `cookies` and with a plain getter). */
export function langOf(cookies: { get(name: string): string | undefined }): AppLang {
	const v = cookies.get('lang');
	return v === 'fr' || v === 'es' ? v : 'en';
}

